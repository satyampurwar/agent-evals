/**
 * Lightweight UUID check (configs/experiments use UUID primary keys).
 * Used when the client may pass either a UUID or some other id string.
 */
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isUuid(value: string): boolean {
  return UUID_RE.test(value);
}
